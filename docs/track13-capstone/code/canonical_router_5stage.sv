`timescale 1ns / 1ps

//=============================================================================
// File: canonical_router_5stage.sv
// Module: canonical_router_5stage
// Description: Synthesizable 5-Stage Pipelined Wormhole NoC Router
//
// Pipeline Architecture:
//   Stage 1: BW (Buffer Write) - Per-port circular VC FIFOs with flow credits
//   Pipeline Reg 1: BW -> RC
//   Stage 2: RC (Route Computation) - Dimension-Order Routing (XY DOR)
//   Pipeline Reg 2: RC -> VA
//   Stage 3: VA (Virtual Channel Allocation) - Downstream VC reservation arbiter
//   Pipeline Reg 3: VA -> SA
//   Stage 4: SA (Switch Allocation) - Separable matrix switch crossbar arbiter
//   Pipeline Reg 4: SA -> ST
//   Stage 5: ST (Switch Traversal) - 5x5 Crossbar multiplexer & link output driver
//
// References:
//   - Dally & Towles, "Principles and Practices of Interconnection Networks", Ch 16
//   - Nangate45 Open Cell Library synthesizable SystemVerilog standard
//=============================================================================

module canonical_router_5stage #(
    parameter integer NUM_PORTS  = 5,    // 0:North, 1:South, 2:East, 3:West, 4:Local
    parameter integer NUM_VCS    = 4,    // Virtual Channels per port
    parameter integer VC_DEPTH   = 4,    // Buffer depth per VC (flits)
    parameter integer FLIT_W     = 64,   // Flit data width (bits)
    parameter integer ROUTER_X   = 1,    // Current tile X coordinate
    parameter integer ROUTER_Y   = 1     // Current tile Y coordinate
)(
    input  wire                               clk,
    input  wire                               rst_n,

    // Ingress Inter-Router Packet Channels (5 Directions: N, S, E, W, L)
    input  wire [NUM_PORTS-1:0]               flit_valid_in,
    input  wire [1:0]                         flit_vc_in [0:NUM_PORTS-1],
    input  wire [FLIT_W-1:0]                  flit_data_in [0:NUM_PORTS-1],
    output reg  [NUM_PORTS-1:0]               credit_out,

    // Egress Inter-Router Packet Channels (5 Directions: N, S, E, W, L)
    output reg  [NUM_PORTS-1:0]               flit_valid_out,
    output reg  [1:0]                         flit_vc_out [0:NUM_PORTS-1],
    output reg  [FLIT_W-1:0]                  flit_data_out [0:NUM_PORTS-1],
    input  wire [NUM_PORTS-1:0]               credit_in,

    // Telemetry & Hardware Diagnostics
    output reg  [31:0]                        flits_routed_count,
    output reg  [31:0]                        buffer_overflow_err
);

    // Directional Port Mapping
    localparam [2:0] PORT_NORTH = 3'd0;
    localparam [2:0] PORT_SOUTH = 3'd1;
    localparam [2:0] PORT_EAST  = 3'd2;
    localparam [2:0] PORT_WEST  = 3'd3;
    localparam [2:0] PORT_LOCAL = 3'd4;

    // Flit Header Decoding
    localparam [1:0] TYPE_HEAD   = 2'b00;
    localparam [1:0] TYPE_BODY   = 2'b01;
    localparam [1:0] TYPE_TAIL   = 2'b10;
    localparam [1:0] TYPE_SINGLE = 2'b11;

    //=========================================================================
    // STAGE 1: BUFFER WRITE (BW) - CIRCULAR VC FIFO STORAGE
    //=========================================================================
    reg [FLIT_W-1:0] vc_mem      [0:NUM_PORTS-1][0:NUM_VCS-1][0:VC_DEPTH-1];
    reg [1:0]        vc_wr_ptr   [0:NUM_PORTS-1][0:NUM_VCS-1];
    reg [1:0]        vc_rd_ptr   [0:NUM_PORTS-1][0:NUM_VCS-1];
    reg [2:0]        vc_count    [0:NUM_PORTS-1][0:NUM_VCS-1];

    // Downstream Flow Control Credit Pool (per egress port and VC)
    reg [2:0] downstream_credits [0:NUM_PORTS-1][0:NUM_VCS-1];

    // Ingress Dequeue signals generated by Stage 5
    wire dequeue_en [0:NUM_PORTS-1][0:NUM_VCS-1];

    integer p, v;
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            buffer_overflow_err <= 32'd0;
            credit_out          <= {NUM_PORTS{1'b0}};
            for (p = 0; p < NUM_PORTS; p = p + 1) begin
                for (v = 0; v < NUM_VCS; v = v + 1) begin
                    vc_wr_ptr[p][v] <= 2'd0;
                    vc_rd_ptr[p][v] <= 2'd0;
                    vc_count[p][v]  <= 3'd0;
                end
            end
        end else begin
            credit_out <= {NUM_PORTS{1'b0}};

            for (p = 0; p < NUM_PORTS; p = p + 1) begin
                if (flit_valid_in[p]) begin
                    if (vc_count[p][flit_vc_in[p]] < VC_DEPTH) begin
                        vc_mem[p][flit_vc_in[p]][vc_wr_ptr[p][flit_vc_in[p]]] <= flit_data_in[p];
                        vc_wr_ptr[p][flit_vc_in[p]] <= (vc_wr_ptr[p][flit_vc_in[p]] + 1'b1) % VC_DEPTH;
                    end else begin
                        buffer_overflow_err <= buffer_overflow_err + 1'b1;
                    end
                end

                for (v = 0; v < NUM_VCS; v = v + 1) begin
                    if (dequeue_en[p][v]) begin
                        vc_rd_ptr[p][v] <= (vc_rd_ptr[p][v] + 1'b1) % VC_DEPTH;
                        credit_out[p]   <= 1'b1;
                    end

                    case ({flit_valid_in[p] && (flit_vc_in[p] == v), dequeue_en[p][v]})
                        2'b10: vc_count[p][v] <= vc_count[p][v] + 1'b1;
                        2'b01: vc_count[p][v] <= vc_count[p][v] - 1'b1;
                        default: vc_count[p][v] <= vc_count[p][v];
                    endcase
                end
            end
        end
    end

    //=========================================================================
    // PIPELINE REGISTER 1: BW -> RC (Buffer Head Latch)
    //=========================================================================
    reg              pr1_valid [0:NUM_PORTS-1][0:NUM_VCS-1];
    reg [FLIT_W-1:0] pr1_flit  [0:NUM_PORTS-1][0:NUM_VCS-1];

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            for (p = 0; p < NUM_PORTS; p = p + 1) begin
                for (v = 0; v < NUM_VCS; v = v + 1) begin
                    pr1_valid[p][v] <= 1'b0;
                    pr1_flit[p][v]  <= {FLIT_W{1'b0}};
                end
            end
        end else begin
            for (p = 0; p < NUM_PORTS; p = p + 1) begin
                for (v = 0; v < NUM_VCS; v = v + 1) begin
                    if (vc_count[p][v] > 0) begin
                        pr1_valid[p][v] <= 1'b1;
                        pr1_flit[p][v]  <= vc_mem[p][v][vc_rd_ptr[p][v]];
                    end else begin
                        pr1_valid[p][v] <= 1'b0;
                    end
                end
            end
        end
    end

    //=========================================================================
    // STAGE 2: ROUTE COMPUTATION (RC) - DIMENSION-ORDER ROUTING (XY DOR)
    //=========================================================================
    reg [2:0] rc_computed_port [0:NUM_PORTS-1][0:NUM_VCS-1];
    reg [2:0] vc_route_state   [0:NUM_PORTS-1][0:NUM_VCS-1];

    reg [1:0] cur_flit_type;
    reg [3:0] cur_dx;
    reg [3:0] cur_dy;

    always @(*) begin
        for (p = 0; p < NUM_PORTS; p = p + 1) begin
            for (v = 0; v < NUM_VCS; v = v + 1) begin
                if (pr1_valid[p][v]) begin
                    cur_flit_type = pr1_flit[p][v][63:62];
                    cur_dx        = pr1_flit[p][v][55:52];
                    cur_dy        = pr1_flit[p][v][51:48];

                    if (cur_flit_type == TYPE_HEAD || cur_flit_type == TYPE_SINGLE) begin
                        if (cur_dx > ROUTER_X)
                            rc_computed_port[p][v] = PORT_EAST;
                        else if (cur_dx < ROUTER_X)
                            rc_computed_port[p][v] = PORT_WEST;
                        else if (cur_dy > ROUTER_Y)
                            rc_computed_port[p][v] = PORT_SOUTH;
                        else if (cur_dy < ROUTER_Y)
                            rc_computed_port[p][v] = PORT_NORTH;
                        else
                            rc_computed_port[p][v] = PORT_LOCAL;
                    end else begin
                        rc_computed_port[p][v] = vc_route_state[p][v];
                    end
                end else begin
                    rc_computed_port[p][v] = PORT_LOCAL;
                end
            end
        end
    end

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            for (p = 0; p < NUM_PORTS; p = p + 1) begin
                for (v = 0; v < NUM_VCS; v = v + 1) begin
                    vc_route_state[p][v] <= PORT_LOCAL;
                end
            end
        end else begin
            for (p = 0; p < NUM_PORTS; p = p + 1) begin
                for (v = 0; v < NUM_VCS; v = v + 1) begin
                    if (pr1_valid[p][v]) begin
                        if (pr1_flit[p][v][63:62] == TYPE_HEAD) begin
                            vc_route_state[p][v] <= rc_computed_port[p][v];
                        end
                    end
                end
            end
        end
    end

    //=========================================================================
    // PIPELINE REGISTER 2: RC -> VA
    //=========================================================================
    reg              pr2_valid [0:NUM_PORTS-1][0:NUM_VCS-1];
    reg [2:0]        pr2_port  [0:NUM_PORTS-1][0:NUM_VCS-1];
    reg [FLIT_W-1:0] pr2_flit  [0:NUM_PORTS-1][0:NUM_VCS-1];

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            for (p = 0; p < NUM_PORTS; p = p + 1) begin
                for (v = 0; v < NUM_VCS; v = v + 1) begin
                    pr2_valid[p][v] <= 1'b0;
                    pr2_port[p][v]  <= PORT_LOCAL;
                    pr2_flit[p][v]  <= {FLIT_W{1'b0}};
                end
            end
        end else begin
            for (p = 0; p < NUM_PORTS; p = p + 1) begin
                for (v = 0; v < NUM_VCS; v = v + 1) begin
                    pr2_valid[p][v] <= pr1_valid[p][v];
                    pr2_port[p][v]  <= rc_computed_port[p][v];
                    pr2_flit[p][v]  <= pr1_flit[p][v];
                end
            end
        end
    end

    //=========================================================================
    // STAGE 3: VIRTUAL CHANNEL ALLOCATION (VA)
    //=========================================================================
    reg [NUM_VCS-1:0] downstream_vc_busy [0:NUM_PORTS-1];
    reg [1:0]         vc_assigned_down   [0:NUM_PORTS-1][0:NUM_VCS-1];

    integer cand_v;
    reg     found_vc;
    reg [2:0] tgt_p;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            for (p = 0; p < NUM_PORTS; p = p + 1) begin
                downstream_vc_busy[p] <= {NUM_VCS{1'b0}};
                for (v = 0; v < NUM_VCS; v = v + 1) begin
                    vc_assigned_down[p][v] <= v[1:0];
                end
            end
        end else begin
            for (p = 0; p < NUM_PORTS; p = p + 1) begin
                for (v = 0; v < NUM_VCS; v = v + 1) begin
                    if (pr2_valid[p][v]) begin
                        tgt_p = pr2_port[p][v];
                        if (pr2_flit[p][v][63:62] == TYPE_HEAD) begin
                            found_vc = 1'b0;
                            for (cand_v = 0; cand_v < NUM_VCS; cand_v = cand_v + 1) begin
                                if (!found_vc && !downstream_vc_busy[tgt_p][cand_v]) begin
                                    vc_assigned_down[p][v]            <= cand_v[1:0];
                                    downstream_vc_busy[tgt_p][cand_v] <= 1'b1;
                                    found_vc                          = 1'b1;
                                end
                            end
                        end else if (pr2_flit[p][v][63:62] == TYPE_TAIL) begin
                            downstream_vc_busy[tgt_p][vc_assigned_down[p][v]] <= 1'b0;
                        end
                    end
                end
            end
        end
    end

    //=========================================================================
    // PIPELINE REGISTER 3: VA -> SA
    //=========================================================================
    reg              pr3_valid   [0:NUM_PORTS-1][0:NUM_VCS-1];
    reg [2:0]        pr3_port    [0:NUM_PORTS-1][0:NUM_VCS-1];
    reg [1:0]        pr3_down_vc [0:NUM_PORTS-1][0:NUM_VCS-1];
    reg [FLIT_W-1:0] pr3_flit    [0:NUM_PORTS-1][0:NUM_VCS-1];

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            for (p = 0; p < NUM_PORTS; p = p + 1) begin
                for (v = 0; v < NUM_VCS; v = v + 1) begin
                    pr3_valid[p][v]   <= 1'b0;
                    pr3_port[p][v]    <= PORT_LOCAL;
                    pr3_down_vc[p][v] <= 2'd0;
                    pr3_flit[p][v]    <= {FLIT_W{1'b0}};
                end
            end
        end else begin
            for (p = 0; p < NUM_PORTS; p = p + 1) begin
                for (v = 0; v < NUM_VCS; v = v + 1) begin
                    pr3_valid[p][v]   <= pr2_valid[p][v];
                    pr3_port[p][v]    <= pr2_port[p][v];
                    pr3_down_vc[p][v] <= vc_assigned_down[p][v];
                    pr3_flit[p][v]    <= pr2_flit[p][v];
                end
            end
        end
    end

    //=========================================================================
    // STAGE 4: SEPARABLE SWITCH ALLOCATION (SA)
    //=========================================================================
    reg [NUM_PORTS-1:0] sa_in_req      [0:NUM_PORTS-1];
    reg [1:0]           sa_in_win_vc   [0:NUM_PORTS-1];
    reg                 sa_in_has_req  [0:NUM_PORTS-1];
    reg [2:0]           tgt_req_p;
    reg [1:0]           tgt_req_vc;

    always @(*) begin
        for (p = 0; p < NUM_PORTS; p = p + 1) begin
            sa_in_req[p]     = {NUM_PORTS{1'b0}};
            sa_in_win_vc[p]  = 2'd0;
            sa_in_has_req[p] = 1'b0;
            for (v = 0; v < NUM_VCS; v = v + 1) begin
                if (pr3_valid[p][v] && !sa_in_has_req[p]) begin
                    tgt_req_p  = pr3_port[p][v];
                    tgt_req_vc = pr3_down_vc[p][v];
                    if (downstream_credits[tgt_req_p][tgt_req_vc] > 0) begin
                        sa_in_req[p][tgt_req_p] = 1'b1;
                        sa_in_win_vc[p]         = v[1:0];
                        sa_in_has_req[p]        = 1'b1;
                    end
                end
            end
        end
    end

    reg [NUM_PORTS-1:0] sa_out_grant     [0:NUM_PORTS-1];
    reg [2:0]           sa_out_winner    [0:NUM_PORTS-1];
    reg                 sa_out_active    [0:NUM_PORTS-1];
    reg [2:0]           out_rr_prio      [0:NUM_PORTS-1];

    integer op_i, ip_i, step_i, cand_p;
    always @(*) begin
        for (ip_i = 0; ip_i < NUM_PORTS; ip_i = ip_i + 1) begin
            sa_out_grant[ip_i] = {NUM_PORTS{1'b0}};
        end

        for (op_i = 0; op_i < NUM_PORTS; op_i = op_i + 1) begin
            sa_out_winner[op_i] = 3'd7;
            sa_out_active[op_i] = 1'b0;
            for (step_i = 0; step_i < NUM_PORTS; step_i = step_i + 1) begin
                cand_p = (out_rr_prio[op_i] + step_i) % NUM_PORTS;
                if (!sa_out_active[op_i] && sa_in_req[cand_p][op_i]) begin
                    sa_out_winner[op_i]         = cand_p[2:0];
                    sa_out_active[op_i]         = 1'b1;
                    sa_out_grant[cand_p][op_i]  = 1'b1;
                end
            end
        end
    end

    //=========================================================================
    // PIPELINE REGISTER 4: SA -> ST (Crossbar Actuation Latch)
    //=========================================================================
    reg              pr4_valid   [0:NUM_PORTS-1];
    reg [2:0]        pr4_in_port [0:NUM_PORTS-1];
    reg [1:0]        pr4_in_vc   [0:NUM_PORTS-1];
    reg [1:0]        pr4_down_vc [0:NUM_PORTS-1];
    reg [FLIT_W-1:0] pr4_flit    [0:NUM_PORTS-1];

    integer win_p_idx;
    reg [1:0] win_v_idx;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            for (op_i = 0; op_i < NUM_PORTS; op_i = op_i + 1) begin
                pr4_valid[op_i]   <= 1'b0;
                pr4_in_port[op_i] <= 3'd0;
                pr4_in_vc[op_i]   <= 2'd0;
                pr4_down_vc[op_i] <= 2'd0;
                pr4_flit[op_i]    <= {FLIT_W{1'b0}};
                out_rr_prio[op_i] <= 3'd0;
            end
        end else begin
            for (op_i = 0; op_i < NUM_PORTS; op_i = op_i + 1) begin
                if (sa_out_active[op_i]) begin
                    win_p_idx = sa_out_winner[op_i];
                    win_v_idx = sa_in_win_vc[win_p_idx];

                    pr4_valid[op_i]   <= 1'b1;
                    pr4_in_port[op_i] <= win_p_idx[2:0];
                    pr4_in_vc[op_i]   <= win_v_idx;
                    pr4_down_vc[op_i] <= pr3_down_vc[win_p_idx][win_v_idx];
                    pr4_flit[op_i]    <= pr3_flit[win_p_idx][win_v_idx];

                    out_rr_prio[op_i] <= (win_p_idx + 1) % NUM_PORTS;
                end else begin
                    pr4_valid[op_i] <= 1'b0;
                end
            end
        end
    end

    genvar gdp, gdv;
    generate
        for (gdp = 0; gdp < NUM_PORTS; gdp = gdp + 1) begin: GEN_DEQ_P
            for (gdv = 0; gdv < NUM_VCS; gdv = gdv + 1) begin: GEN_DEQ_V
                assign dequeue_en[gdp][gdv] = (sa_out_active[0] && sa_out_winner[0] == gdp && sa_in_win_vc[gdp] == gdv) ||
                                              (sa_out_active[1] && sa_out_winner[1] == gdp && sa_in_win_vc[gdp] == gdv) ||
                                              (sa_out_active[2] && sa_out_winner[2] == gdp && sa_in_win_vc[gdp] == gdv) ||
                                              (sa_out_active[3] && sa_out_winner[3] == gdp && sa_in_win_vc[gdp] == gdv) ||
                                              (sa_out_active[4] && sa_out_winner[4] == gdp && sa_in_win_vc[gdp] == gdv);
            end
        end
    endgenerate

    //=========================================================================
    // STAGE 5: SWITCH TRAVERSAL (ST) & LINK OUTPUT DRIVER
    //=========================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            flit_valid_out     <= {NUM_PORTS{1'b0}};
            flits_routed_count <= 32'd0;
            for (op_i = 0; op_i < NUM_PORTS; op_i = op_i + 1) begin
                flit_vc_out[op_i]   <= 2'd0;
                flit_data_out[op_i] <= {FLIT_W{1'b0}};
                for (v = 0; v < NUM_VCS; v = v + 1) begin
                    downstream_credits[op_i][v] <= VC_DEPTH[2:0];
                end
            end
        end else begin
            for (op_i = 0; op_i < NUM_PORTS; op_i = op_i + 1) begin
                if (pr4_valid[op_i]) begin
                    flit_valid_out[op_i] <= 1'b1;
                    flit_vc_out[op_i]    <= pr4_down_vc[op_i];
                    flit_data_out[op_i]  <= pr4_flit[op_i];
                    flits_routed_count   <= flits_routed_count + 1'b1;

                    if (downstream_credits[op_i][pr4_down_vc[op_i]] > 0)
                        downstream_credits[op_i][pr4_down_vc[op_i]] <= downstream_credits[op_i][pr4_down_vc[op_i]] - 1'b1;
                end else begin
                    flit_valid_out[op_i] <= 1'b0;
                    flit_data_out[op_i]  <= {FLIT_W{1'b0}};
                end

                if (credit_in[op_i]) begin
                    for (v = 0; v < NUM_VCS; v = v + 1) begin
                        if (downstream_credits[op_i][v] < VC_DEPTH)
                            downstream_credits[op_i][v] <= downstream_credits[op_i][v] + 1'b1;
                    end
                end
            end
        end
    end

endmodule
